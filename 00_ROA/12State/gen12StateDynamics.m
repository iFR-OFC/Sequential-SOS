function xdot = gen12StateDynamics(x)

%% -----------------------------------------------------------------------
% Short Description: Implements the 12 state dynamical system
% found in the Appendix of [1].
%
% Reference :
%  [1]	- J. Anderson und A. Papachristodoulou, „Dynamical system
%         decomposition for efficient, sparse analysis", in 49th 
%         IEEE Conf Dec. Con. 2010,  doi: 10.1109/CDC.2010.5717269.
% -----------------------------------------------------------------------


dx_1 = -1.47*x(1) - 0.574*x(2) - 0.583*x(3) + 0.942*x(4) + 0.714*x(5) ...
        + 1.35*x(6) + 0.861*x(7) + 1.51*x(9) + 1.10*x(11) + 1.14*x(12) ...
        + x(2)*x(6)*x(9);

dx_2 = -0.760*x(2) + 1.54*x(3) - 1.63*x(4) - 0.819*x(5) - 0.925*x(6) ...
        - 1.06*x(7) - 0.535*x(10) + 0.681*x(11) + x(7)*x(10)*x(11);

dx_3 = 1.77*x(1) - 0.983*x(2) - 0.766*x(3) - 0.930*x(6) - 1.13*x(9) ...
        - 0.998*x(10) + 1.84*x(11) + 0.772*x(12) + x(3)^3;

dx_4 = -1.37*x(1) + 1.31*x(2) + 0.790*x(3) - 0.572*x(4) - 1.07*x(5) ...
        - 0.783*x(6) - 0.938*x(8) + 2.03*x(9) - 0.857*x(11) ...
        + x(4)*x(8)*x(11);

dx_5 = -1.04*x(1) + 0.755*x(2) + 1.12*x(4) - 0.538*x(5) - 0.563*x(8) ...
        + 1.40*x(9) - 1.32*x(11) + x(1)*x(2)*x(5);

dx_6 = 1.26*x(2) + 1.11*x(4) - 0.885*x(6) - 0.935*x(8) + 1.05*x(9) ...
        - 1.30*x(11) + x(2)*x(4)*x(11);

dx_7 = -0.845*x(1) - 1.67*x(7) + 1.72*x(9) + 0.839*x(10) - 1.25*x(11) ...
        - 0.600*x(12) + x(1)*x(7)*x(11);

dx_8 = 0.583*x(1) + 1.20*x(4) + 0.816*x(5) + 0.599*x(6) - 0.735*x(9) ...
        + x(1)^3;

dx_9 = -1.25*x(1) + 1.04*x(2) + 0.990*x(3) - 1.44*x(4) - 1.44*x(5) ...
        - 1.29*x(6) - 1.20*x(9) - 1.16*x(10) - 3.15*x(11) - 0.998*x(12) ...
        + x(1)*x(6)*x(10);

dx_10 = 1.43*x(2) + 0.835*x(3) + 0.545*x(7) - 0.890*x(8) - 0.973*x(10) ...
         + x(2)*x(3)*x(8);

dx_11 = -2.29*x(3) + 1.41*x(4) + 1.43*x(5) + 0.512*x(6) + 2.00*x(7) ...
         - 0.801*x(8) + 2.46*x(9) - 0.659*x(10) - 0.833*x(11) + 1.29*x(12) ...
         + x(6)^3;

dx_12 = -0.850*x(1) - 0.919*x(3) + 0.515*x(7) + 1.20*x(9) - 1.25*x(11) ...
         + x(1)*x(9)*x(11);

xdot = [dx_1;dx_2;dx_3;dx_4;dx_5;dx_6;dx_7;dx_8;dx_9;dx_10;dx_11;dx_12];

end