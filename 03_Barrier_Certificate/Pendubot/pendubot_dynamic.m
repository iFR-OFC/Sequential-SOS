function xdot = pendubot_dynamic(x,u)

f2 = -10.656*x(1)^4 + 11.531*x(1)^2*x(3) + 7.885*x(1)*x(3)^2 ...
    + 0.797*x(2)^2*x(3) + 0.841*x(2)*x(3)*x(4) + 21.049*x(3)^3 ...
    + 0.420*x(3)^2*x(4) + 66.523*x(1) - 24.511*x(3);

f4 = 10.996*x(1)^3 - 48.915*x(1)^2*x(3) - 6.404*x(1)*x(3)^2 ...
    - 2.396*x(2)^2*x(3) - 1.594*x(2)*x(3)*x(4) - 51.909*x(3)^3 ...
    - 0.797*x(3)^2*x(4) - 68.642*x(1) + 103.978*x(3);

g2 = -10.096*x(3)^2 + 44.252;
g4 = 37.802*x(3)^2 - 83.912;

xdot = [x(2); f2; x(4); f4] + [0; g2; 0; g4]*u;

end
