    + 3.939*x(3)^3 + 21.520*x(1) - 5.000*x(3);
f4 =  4.023*x(1)^3 - 36.551*x(1)^2*x(3) - 4.131*x(2)^2*x(3) ...
    - 27.060*x(3)^3 - 25.115*x(1) + 77.700*x(3);


